function detectLanguage(deviceLanguage = navigator.language) {
  const language = String(deviceLanguage || "").toLowerCase().split(/[-_]/)[0];
  return supportedLanguages.includes(language) ? language : "en";
}

function setLanguage(language, remember = false) {
  const selected = supportedLanguages.includes(language) ? language : "en";
  const index = supportedLanguages.indexOf(selected);
  document.documentElement.lang = selected;
  document.querySelectorAll("[data-i18n]").forEach(element => {
    const value = translations[element.dataset.i18n];
    if (value) element.textContent = value[index];
  });
  document.querySelectorAll("[data-i18n-aria]").forEach(element => {
    const value = translations[element.dataset.i18nAria];
    if (value) element.setAttribute("aria-label", value[index]);
  });
  const description = document.querySelector('meta[name="description"]');
  if (description) description.content = description.getAttribute(`data-description-${selected}`) || translations.description[index];
  document.querySelectorAll("[data-language-content]").forEach(element => {
    element.hidden = element.dataset.languageContent !== selected;
  });
  const pageTitle = document.body.getAttribute(`data-title-${selected}`);
  if (pageTitle) document.title = pageTitle;
  document.querySelectorAll("[data-language]").forEach(button => {
    button.setAttribute("aria-pressed", String(button.dataset.language === selected));
  });
  if (remember) {
    manualLanguage = selected;
    try { localStorage.setItem("tyliaitpk-language", selected); } catch {}
  }
  if (typeof galleryDialog !== "undefined" && galleryDialog.open) renderGalleryImage();
}

