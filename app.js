let previousOverflow = "";

function renderGalleryImage() {
  const image = galleryImages[galleryIndex];
  if (!image) return;
  const display = galleryDialog.querySelector(".gallery-image");
  display.src = image.href;
  display.alt = image.alt;
  galleryDialog.querySelector("#gallery-title").textContent = galleryName;
  galleryDialog.querySelector(".gallery-counter").textContent = `${galleryIndex + 1} / ${galleryImages.length}`;
  galleryDialog.querySelector(".gallery-previous").disabled = galleryImages.length < 2;
  galleryDialog.querySelector(".gallery-next").disabled = galleryImages.length < 2;
}
function moveGallery(direction) {
  galleryIndex = (galleryIndex + direction + galleryImages.length) % galleryImages.length;
  renderGalleryImage();
}
